import { chromium, expect } from '@playwright/test';
import { PDFDocument } from 'pdf-lib';
import { mkdir } from 'node:fs/promises';
await mkdir('tmp', { recursive: true });
const url=process.env.BASE_URL ?? 'https://sdafik.github.io/tender-document-package-builder/';
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const failures=[];const errors=[];const outgoing=[];
page.on('requestfailed',r=>failures.push(r.url()));page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.method()!=='GET')outgoing.push({url:r.url(),method:r.method()});});
const response=await page.goto(url,{waitUntil:'networkidle'});expect(response.status()).toBe(200);
await expect(page.getByRole('heading',{name:'A complete bid starts here.'})).toBeVisible();
const data={tender:{tender_id:'LIVE-CHECK',title:'Live verification',procuring_entity:'QA',bidder:'QA',submission_deadline:'2026-10-20'},requirements:[{id:'certificate',order:1,title_en:'Certificate',title_bn:'সনদ',mandatory:true,has_expiry:true}]};
await page.getByLabel('Load tender',{exact:true}).setInputFiles({name:'requirements.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))});
const pdf=await PDFDocument.create();pdf.addPage([400,500]);
await page.getByLabel('Upload PDFs',{exact:true}).setInputFiles({name:'certificate.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save())});
await expect(page.getByLabel('Upload PDFs',{exact:true})).toBeEnabled();
await expect(page.locator('.file-row')).toHaveCount(1);
const select=page.locator('.requirement select');await select.selectOption(await select.locator('option').nth(1).getAttribute('value'));
await page.getByLabel('Expiry for Certificate',{exact:true}).fill('2026-10-20');
await expect(page.getByRole('button',{name:'Generate package',exact:true})).toBeEnabled();
const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Generate package',exact:true}).click();
const download=await pending;expect(download.suggestedFilename()).toBe('LIVE-CHECK_Package.pdf');await download.saveAs('tmp/pages-smoke.pdf');
await page.getByRole('button',{name:'বাংলা',exact:true}).click();await expect(page.locator('.requirement h3')).toHaveText('সনদ');
await page.screenshot({path:'tmp/github-pages.png',fullPage:true});
expect(failures).toEqual([]);expect(errors).toEqual([]);expect(outgoing).toEqual([]);
console.log('Live GitHub Pages verified: HTTP 200, assets and PDF worker load, expiry equality passes, PDF downloads, Bangla works, no failed requests or document upload requests.');
await browser.close();

